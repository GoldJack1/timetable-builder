import { uid } from "./model";
import type { DirectionBlock, Panel, StopRow, TimetableDoc } from "./types";

function block(rows: StopRow[], columns: string[][], noteIcons: string[][] = []): DirectionBlock {
  return {
    rows,
    services: columns.map((col, i) => ({
      id: uid(),
      noteIconIds: noteIcons[i] ?? [],
      times: Object.fromEntries(
        rows.map((row, r) => {
          const value = col[r] ?? "";
          return [
            row.stationId,
            {
              value,
              ...(row.stationId === "damems" && value && value !== "-" ? { style: "italic" as const } : {}),
            },
          ];
        }),
      ),
    })),
  };
}

function panel(
  letter: string,
  outRows: StopRow[],
  inRows: StopRow[],
  outCols: string[][],
  inCols: string[][],
  outNotes: string[][] = [],
  inNotes: string[][] = [],
): Panel {
  return {
    id: uid(),
    letter,
    outbound: block(outRows, outCols, outNotes),
    inbound: block(inRows, inCols, inNotes),
  };
}

